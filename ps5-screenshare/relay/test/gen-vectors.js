#!/usr/bin/env node
/* Generates the shared test vectors for the secure channel, using Node's own
 * crypto module as the reference. The C, Java and Windows implementations are
 * tested against these same values.
 *
 *   node relay/test/gen-vectors.js
 *
 * Writes:
 *   relay/test/vectors.json                 (reference)
 *   payload/tests/secure_vectors.h           (C test)
 *   android/.../test/SecureVectors.java      (Java test)
 *
 * Copyright (C) 2026 PS5 Screen Share contributors
 * SPDX-License-Identifier: GPL-3.0-or-later
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const ROOT = path.resolve(__dirname, '..', '..');

const sha256 = (...parts) => {
  const h = crypto.createHash('sha256');
  for (const p of parts) h.update(p);
  return h.digest();
};

// Derivations, exactly as documented in relay/PROTOCOL.md
const pairingId = (secret) => sha256(Buffer.from('ps5ss-id-v1'), secret).subarray(0, 8).toString('hex');
const pairingKey = (secret) => sha256(Buffer.from('ps5ss-key-v1'), secret);
const sessionKey = (key, salt) => sha256(Buffer.from('ps5ss-sess-v1'), key, salt);

function nonce(dir, seq) {
  const n = Buffer.alloc(12);
  n[0] = dir;
  n.writeBigUInt64BE(BigInt(seq), 4);
  return n;
}

function seal(key, dir, seq, plain) {
  const c = crypto.createCipheriv('chacha20-poly1305', key, nonce(dir, seq), { authTagLength: 16 });
  const ct = Buffer.concat([c.update(plain), c.final()]);
  return Buffer.concat([ct, c.getAuthTag()]);
}

const secrets = [
  '00112233445566778899aabbccddeeff',
  'a1b2c3d4e5f60718293a4b5c6d7e8f90',
  'ffffffffffffffffffffffffffffffff',
];
const salts = ['000102030405060708090a0b0c0d0e0f', 'deadbeefdeadbeefdeadbeefdeadbeef'];
const lengths = [0, 1, 15, 16, 17, 63, 64, 65, 255, 1000, 4097];

const vectors = { pairing: [], session: [], frames: [] };
for (const hex of secrets) {
  const secret = Buffer.from(hex, 'hex');
  const key = pairingKey(secret);
  vectors.pairing.push({ secret: hex, id: pairingId(secret), key: key.toString('hex') });
  for (const s of salts) {
    const salt = Buffer.from(s, 'hex');
    vectors.session.push({ key: key.toString('hex'), salt: s, sessionKey: sessionKey(key, salt).toString('hex') });
  }
}

const frameKey = sessionKey(pairingKey(Buffer.from(secrets[1], 'hex')), Buffer.from(salts[0], 'hex'));
let i = 0;
for (const dir of [0x43, 0x53]) {
  for (const seq of [0, 1, 7]) {
    for (const len of lengths) {
      const plain = Buffer.alloc(len);
      for (let k = 0; k < len; k++) plain[k] = (k * 31 + len + seq + i) & 0xff;
      i++;
      vectors.frames.push({
        key: frameKey.toString('hex'),
        dir,
        seq,
        nonce: nonce(dir, seq).toString('hex'),
        plain: plain.toString('hex'),
        body: seal(frameKey, dir, seq, plain).toString('hex'),
      });
    }
  }
}

// SHA-256 on its own, for the lengths around the block boundaries.
vectors.sha = [];
for (const len of [0, 1, 55, 56, 63, 64, 65, 119, 120, 128, 1000]) {
  const data = Buffer.alloc(len, 0x61 + (len % 26));
  vectors.sha.push({ data: data.toString('hex'), digest: crypto.createHash('sha256').update(data).digest('hex') });
}

const json = JSON.stringify(vectors, null, 1);
fs.writeFileSync(path.join(__dirname, 'vectors.json'), json + '\n');

// --- C header -----------------------------------------------------------
const bytesC = (hex) => {
  const b = Buffer.from(hex, 'hex');
  return b.length ? [...b].map((x) => '0x' + x.toString(16).padStart(2, '0')).join(',') : '0';
};
let c = '/* GENERATED by relay/test/gen-vectors.js - do not edit. */\n#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n';
c += 'typedef struct { const char *secret; const char *id; const uint8_t key[32]; } vec_pairing;\n';
c += 'typedef struct { const uint8_t key[32]; const uint8_t salt[16]; const uint8_t session[32]; } vec_session;\n';
c += 'typedef struct { const uint8_t key[32]; uint8_t dir; uint64_t seq; const uint8_t *plain; size_t plain_len; const uint8_t *body; size_t body_len; } vec_frame;\n';
c += 'typedef struct { const uint8_t *data; size_t len; const uint8_t digest[32]; } vec_sha;\n\n';
const hexArr = (name, hex) => `static const uint8_t ${name}[] = {${bytesC(hex)}};\n`;
vectors.pairing.forEach((v, n) => {
  c += hexArr('pair_key_' + n, v.key);
});
c += 'static const vec_pairing VEC_PAIRING[] = {\n';
vectors.pairing.forEach((v, n) => { c += `  {"${v.secret}", "${v.id}", {${bytesC(v.key).replace(/0x/g, '0x')}}},\n`; });
c += '};\n';
c += `#define VEC_PAIRING_COUNT ${vectors.pairing.length}\n\n`;
vectors.session.forEach((v, n) => {
  c += hexArr('sess_key_' + n, v.key);
  c += hexArr('sess_salt_' + n, v.salt);
  c += hexArr('sess_out_' + n, v.sessionKey);
});
c += 'static const vec_session VEC_SESSION[] = {\n';
vectors.session.forEach((v, n) => { c += `  {{${bytesC(v.key)}}, {${bytesC(v.salt)}}, {${bytesC(v.sessionKey)}}},\n`; });
c += '};\n';
c += `#define VEC_SESSION_COUNT ${vectors.session.length}\n\n`;
vectors.frames.forEach((v, n) => {
  c += hexArr('frame_plain_' + n, v.plain);
  c += hexArr('frame_body_' + n, v.body);
});
c += 'static const vec_frame VEC_FRAME[] = {\n';
vectors.frames.forEach((v, n) => {
  c += `  {{${bytesC(v.key)}}, ${v.dir}, ${v.seq}ULL, frame_plain_${n}, ${v.plain.length / 2}, frame_body_${n}, ${v.body.length / 2}},\n`;
});
c += '};\n';
c += `#define VEC_FRAME_COUNT ${vectors.frames.length}\n\n`;
vectors.sha.forEach((v, n) => {
  c += hexArr('sha_data_' + n, v.data);
});
c += 'static const vec_sha VEC_SHA[] = {\n';
vectors.sha.forEach((v, n) => { c += `  {sha_data_${n}, ${v.data.length / 2}, {${bytesC(v.digest)}}},\n`; });
c += '};\n';
c += `#define VEC_SHA_COUNT ${vectors.sha.length}\n`;
fs.writeFileSync(path.join(ROOT, 'payload', 'tests', 'secure_vectors.h'), c);

// --- Java ---------------------------------------------------------------
const javaBytes = (hex) => {
  const b = Buffer.from(hex, 'hex');
  return b.length ? [...b].map((x) => (x > 127 ? x - 256 : x) + '').join(', ') : '';
};
let j = '/* GENERATED by relay/test/gen-vectors.js - do not edit. */\npackage com.ps5screenshare.client;\n\n';
j += 'final class SecureVectors {\n    private SecureVectors() {}\n\n';
j += '    static final String[][] PAIRING = {\n';
vectors.pairing.forEach((v) => { j += `        {"${v.secret}", "${v.id}", "${v.key}"},\n`; });
j += '    };\n\n';
j += '    static final String[][] SESSION = {\n';
vectors.session.forEach((v) => { j += `        {"${v.key}", "${v.salt}", "${v.sessionKey}"},\n`; });
j += '    };\n\n';
j += '    static final String[][] FRAMES = {\n';
vectors.frames.forEach((v) => { j += `        {"${v.key}", "${v.dir.toString(16)}", "${v.seq}", "${v.nonce}", "${v.plain}", "${v.body}"},\n`; });
j += '    };\n\n';
j += '    static final String[][] SHA = {\n';
vectors.sha.forEach((v) => { j += `        {"${v.data}", "${v.digest}"},\n`; });
j += '    };\n}\n';
void javaBytes;
fs.writeFileSync(path.join(ROOT, 'android', 'app', 'src', 'test', 'java', 'com', 'ps5screenshare', 'client', 'SecureVectors.java'), j);

console.log('vectors: pairing ' + vectors.pairing.length + ', session ' + vectors.session.length +
  ', frames ' + vectors.frames.length + ', sha ' + vectors.sha.length);
