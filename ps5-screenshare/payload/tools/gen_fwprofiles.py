#!/usr/bin/env python3
"""Generate src/fwprofiles_data.h from PBS-Payload's measured PS5 profiles.

The request geometry tables (sizes, group offsets, constant initializers) were
measured by the PBS-Payload project (GPL-3.0-or-later,
https://github.com/the-mentor/PBS-Payload, payload/src/platform/ps5/offset/).
This script only converts them to a compact C table.

usage: gen_fwprofiles.py <PBS checkout>/payload/src/platform/ps5/offset out.h
"""
import os
import re
import sys


def num(text):
    return int(text.rstrip("u"), 0)


def parse(path):
    src = open(path, encoding="utf-8").read()
    inits = []
    for m in re.finditer(r"\{ \.offset = (0x[0-9a-f]+)u, \.size = (0x[0-9a-f]+)u, "
                         r"\.bytes = \{ ([^}]*) \} \}", src):
        data = [num(b.strip()) for b in m.group(3).split(",") if b.strip()]
        inits.append((num(m.group(1)), num(m.group(2)), data))

    def field(name, scope=src):
        m = re.search(r"\." + name + r" = (0x[0-9a-f]+)u", scope)
        return num(m.group(1)) if m else 0

    def group(name):
        m = re.search(r"\." + name + r" = \{(.*?)\}", src, re.S)
        return (field("offset", m.group(1)), field("size", m.group(1)),
                field("descriptor_size", m.group(1)))

    return {
        "fw": field("firmware"),
        "request_size": field("request_size"),
        "kind": field("kind_offset"),
        "rate": group("rate"),
        "image": group("image"),
        "width": field("width_offset"),
        "height": field("height_offset"),
        "paste": field("paste_offset"),
        "vmode": field("video_mode_offset"),
        "mask": field("mask_mode_offset"),
        "mask_span": field("mask_span") or 0x24,
        "inits": inits,
    }


def main():
    src_dir, out = sys.argv[1], sys.argv[2]
    profiles = []
    for name in os.listdir(src_dir):
        if re.fullmatch(r"\d+\.c", name):
            profiles.append(parse(os.path.join(src_dir, name)))
    profiles.sort(key=lambda p: p["fw"])
    lines = [
        "/* GENERATED by tools/gen_fwprofiles.py - do not edit.",
        " *",
        " * PS5 libSceAvcap2 OpenVideo request geometry per firmware, as measured",
        " * by PBS-Payload (GPL-3.0-or-later, https://github.com/the-mentor/PBS-Payload).",
        " */",
        "#include \"fwprofiles.h\"",
        "",
    ]
    for p in profiles:
        tag = "%08x" % p["fw"]
        lines.append("static const fw_init init_%s[] = {" % tag)
        for off, size, data in p["inits"]:
            assert size == len(data), (tag, off)
            lines.append("  {0x%03x, %d, {%s}}," % (off, size, ", ".join("0x%02x" % b for b in data)))
        lines.append("};")
    lines.append("")
    lines.append("const fw_profile fw_profiles[] = {")
    for p in profiles:
        tag = "%08x" % p["fw"]
        r, i = p["rate"], p["image"]
        lines.append(
            "  {0x%sU, 0x%03x, 0x%03x, {0x%03x, 0x%03x, 0x%02x}, {0x%03x, 0x%03x, 0x%02x}, "
            "0x%03x, 0x%03x, 0x%03x, 0x%03x, 0x%03x, 0x%02x, init_%s, %d},"
            % (tag, p["request_size"], p["kind"], r[0], r[1], r[2], i[0], i[1], i[2],
               p["width"], p["height"], p["paste"], p["vmode"], p["mask"], p["mask_span"],
               tag, len(p["inits"])))
    lines.append("};")
    lines.append("const unsigned fw_profile_count = sizeof(fw_profiles) / sizeof(fw_profiles[0]);")
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
